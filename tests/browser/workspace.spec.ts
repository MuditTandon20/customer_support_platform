import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('agent workspace: signup, knowledge, conversation, cited draft, reply, workflow and analytics',async({page})=>{
 const suffix=Date.now();
 await page.goto('/signup');
 await page.getByLabel('Organization name').fill(`Demo QA ${suffix}`);
 await page.getByLabel('Full name',{exact:true}).fill('Demo Agent');
 await page.getByLabel('Email address').fill(`browser-${suffix}@example.test`);
 await page.getByLabel('Password',{exact:true}).fill('Browser-test-password-2026!');
 await page.getByRole('button',{name:'Create workspace'}).click();
 await expect(page.getByRole('heading',{name:'A thoughtful setup, from the start.'})).toBeVisible();
 expect(await page.evaluate(()=>localStorage.getItem('auth_token'))).toBe('cookie-session');
 await page.getByRole('link',{name:'Knowledge',exact:true}).click();
 await page.getByRole('button',{name:'Add article'}).click();
 await page.getByLabel('Title',{exact:true}).fill('Refund policy');
 await page.getByLabel('Article content').fill('Refund policy: requests are reviewed within five business days.');
 await page.getByRole('button',{name:'Save and index'}).click();
 await expect(page.getByRole('button',{name:'Refund policy',exact:true})).toBeVisible();
 await page.goto('/tickets/new');
 await page.getByPlaceholder('Brief description of the issue').fill('Refund policy');
 await page.getByPlaceholder('Provide details about the issue').fill('Refund policy');
 await page.getByRole('button',{name:'Create Ticket'}).click();
 await expect(page.getByRole('heading',{name:'Refund policy',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Find evidence & draft'}).click();
 await expect(page.getByText('Suggested · Not sent',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Use in reply editor'}).click();
 await expect(page.getByLabel('Your reply',{exact:true})).toHaveValue(/Refund policy/);
 await page.getByRole('button',{name:'Send portal reply'}).click();
 await expect(page.getByText('Visible in the customer portal',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Internal note',exact:true}).click();
 await page.getByLabel('Note for your team').fill('QA internal note');
 await page.getByRole('button',{name:'Save internal note'}).click();
 await expect(page.getByText('QA internal note',{exact:true})).toBeVisible();
 await page.getByRole('link',{name:'Workflows',exact:true}).click();
 await page.getByRole('button',{name:'Save draft',exact:true}).click();
 await expect(page.getByText('Draft saved. Publish it before running against a ticket.')).toBeVisible();
 await page.getByRole('button',{name:'Publish version'}).click();
 await expect(page.getByText('Version 1 published. Execution uses this saved version.')).toBeVisible();
 await page.getByRole('combobox',{name:'Conversation to test'}).selectOption({label:'Refund policy'});
 await page.getByRole('button',{name:/Simulate/}).click();
 await expect(page.getByRole('heading',{name:'Simulation trace · awaiting_human'})).toBeVisible();
 await page.getByRole('link',{name:'Overview',exact:true}).click();
 await expect(page.getByRole('heading',{name:'A little clarity. A lot of progress.'})).toBeVisible();
 await page.screenshot({path:'../docs/screenshots/workspace-desktop.png',fullPage:true});
 await page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(a=>a.effect?.getComputedTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{})));});
 const a11y=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
 expect(a11y.violations.filter(v=>v.impact==='serious'||v.impact==='critical')).toEqual([]);
 await page.keyboard.press('Control+k');
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByLabel('Go to a page').fill('Analytics');
 await page.getByRole('navigation',{name:'Page search'}).getByRole('link',{name:'Analytics'}).click();
 await expect(page.getByRole('heading',{name:'Clarity, backed by events.'})).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'../docs/screenshots/workspace-mobile.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 for(const module of ['inbox','knowledge','activity','workflows','customers','approvals','integrations','billing','settings','audit']){await page.goto(`/workspace/${module}`);await expect(page.locator('#workspace-content h1')).toBeVisible();expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${module} mobile overflow`).toBeTruthy();await page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(a=>a.effect?.getComputedTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{})));});const result=await new AxeBuilder({page}).withTags(["wcag2a","wcag2aa","wcag21aa"]).analyze();expect(result.violations.filter(v=>v.impact==="serious"||v.impact==="critical"),`${module} accessibility`).toEqual([]);}
 await page.getByRole('button',{name:'Toggle navigation'}).click();
 await expect(page.getByRole('navigation',{name:'Workspace'})).toBeVisible();
 await page.getByRole('button',{name:'Light appearance'}).click();
 await expect(page.locator('.workspace')).toHaveAttribute('data-theme','light');
 await page.goto('/workspace/dashboard');
 await expect(page.locator('.workspace')).toHaveAttribute('data-theme','light');
 await expect(page.locator('.metric-card').first()).toBeVisible();
 await page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(a=>a.effect?.getComputedTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{})));});
 const lightA11y=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
 expect(lightA11y.violations.filter(v=>v.impact==='serious'||v.impact==='critical')).toEqual([]);
 await page.screenshot({path:'../docs/screenshots/workspace-light.png',fullPage:true});
});

test('marketing and login support reduced motion and mobile layout',async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.setViewportSize({width:390,height:844});
 await page.goto('/');
 await expect(page.getByRole('heading',{level:1})).toContainText('Less noise.');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.goto('/login');
 await expect(page.getByLabel('Email address')).toBeVisible();
 await expect(page.getByLabel('Password',{exact:true})).toBeVisible();
 await page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(a=>a.effect?.getComputedTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{})));});
 const a11y=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
 expect(a11y.violations.filter(v=>v.impact==='serious'||v.impact==='critical')).toEqual([]);
 await page.screenshot({path:'../docs/screenshots/login-mobile.png',fullPage:true});
});
