import {chromium} from '@playwright/test';
if(!process.env.DEMO_EMAIL)throw new Error('Set DEMO_EMAIL to the explicitly labeled local demo account');
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const base=process.env.TEST_WEB_URL||'http://localhost:13000';
await page.goto(base+'/login');
await page.getByLabel('Email address').fill(process.env.DEMO_EMAIL);
await page.getByLabel('Password',{exact:true}).fill(process.env.DEMO_PASSWORD||'Demo-only-password-2026!');
await page.getByRole('button',{name:'Sign in',exact:false}).click();
await page.waitForURL('**/workspace/dashboard');
await page.locator('.metric-card').first().waitFor();
await page.screenshot({path:'../docs/screenshots/demo-dashboard.png',fullPage:true});
await page.goto(base+'/workspace/inbox');
await page.locator('tbody tr').first().waitFor();
await page.screenshot({path:'../docs/screenshots/demo-inbox.png',fullPage:true});
await page.goto(base+'/workspace/workflows');
await page.getByRole('combobox',{name:/^Workflow/}).selectOption({label:'Demo · Review before action · v1'});
await page.screenshot({path:'../docs/screenshots/demo-workflows.png',fullPage:true});
await page.goto(base+'/workspace/dashboard');
await page.locator('.metric-card').first().waitFor();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'../docs/screenshots/demo-mobile.png',fullPage:true});
await browser.close();
